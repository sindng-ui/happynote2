import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Obsidian Ear-Coach Plugin (YouTube + Obsidian + agy CLI)
*/
`;

const prod = process.argv[2] === "production";

// First bundle the Web Worker into an inlineable string or standalone worker code
const workerBuild = await esbuild.build({
  entryPoints: ["src/workers/transcript.worker.ts"],
  bundle: true,
  write: false,
  format: "iife",
  target: "es2022",
  minify: prod,
});

const workerCode = workerBuild.outputFiles[0].text;

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["src/main.ts"],
  bundle: true,
  define: {
    __INLINE_WORKER_CODE__: JSON.stringify(workerCode),
  },
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2022",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
